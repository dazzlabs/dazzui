import fs from 'node:fs'
import { SPACING_STEPS } from './schema/scene.mjs'

const css = fs.readFileSync(
  new URL(
    '../../packages/js/dazzui-react/src/generated/style.css',
    import.meta.url
  ),
  'utf8'
)
/** A spacing step's logical length in the default theme, read from ds output. */
export function spacingPixels(token) {
  const name = token.replace('spacing.', 'spacing-')
  const match = new RegExp(`--${name}:\\s*([\\d.]+)rem;`).exec(css)
  if (!match) throw Error(`No ds value for ${token}`)
  // ds states lengths in rem against the 16px root the web and ports share.
  return Number(match[1]) * 16
}
for (const step of SPACING_STEPS) spacingPixels(step)

const step = token => token.split('.')[1]
/** Theme accessors for a spacing step, in each platform's generated names. */
export const spacing = {
  react: token => `var(--${token.replace('.', '-')})`,
  dart: token => `spacing${step(token).replace('-', '')}`,
  swift: token => `theme.vars.spacing${step(token).replace('-', '')}`,
}

/** Token lookups the interpreted runtimes cannot derive by reflection. */
export function tokenOutputs() {
  const header =
    '// Generated by tools/playgrounds. Edit tools/playgrounds/schema/scene.mjs.\n'
  return new Map([
    [
      'packages/dart/dazzui/example/lib/generated/spacing.dart',
      `${header}import 'package:dazzui/dazzui.dart';

/// The theme's length for a declared spacing step.
double sceneSpacing(ThemeVariables vars, String step) => switch (step) {
${SPACING_STEPS.map(token => `  '${token}' => vars.${spacing.dart(token)},`).join('\n')}
  _ => throw StateError('Unsupported spacing: $step'),
};
`,
    ],
    [
      'packages/kotlin/dazzui-mobile/example/src/main/kotlin/dev/dazzlabs/dazzui/mobile/example/GeneratedSpacing.kt',
      `${header}package dev.dazzlabs.dazzui.mobile.example

/** ds spacing steps in logical pixels; mobile draws them on its dp grid. */
internal val sceneSpacing: Map<String, Float> = mapOf(
${SPACING_STEPS.map(token => `    "${token}" to ${spacingPixels(token)}f,`).join('\n')}
)
`,
    ],
  ])
}
