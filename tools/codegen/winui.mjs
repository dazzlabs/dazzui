import { SUPPORT as FLUTTER_SUPPORT } from './flutter.mjs'
import { gaps } from './support.mjs'

/*
 * The WinUI 3 example's generated sources: the stories as data, the glyphs
 * they name, and the themes the window offers.
 *
 * `SUPPORT` is the contract with the WinUI scene interpreter
 * (`example/Lib/Mapping.cs`), as Flutter's is with its own. The three
 * draw the same components today, so the list starts as Flutter's; it is
 * WinUI's to narrow or widen.
 */
export const SUPPORT = structuredClone(FLUTTER_SUPPORT)

/** Every component and prop a story sets that WinUI does not draw. */
export const unsupported = stories => gaps(stories, SUPPORT, 'WinUI')

const header =
  '// Generated by tools/codegen from the React example. Do not edit.\n'

const pascal = id =>
  id.replace(/(^|-)([a-z0-9])/g, (_, __, letter) => letter.toUpperCase())

/** A story's file name on WinUI: the React file's, in C#'s casing. */
export const storyFile = id => `${pascal(id)}.cs`

/** A C# raw string literal fence longer than any run of quotes inside. */
function fence(text) {
  const longest = Math.max(0, ...(text.match(/"+/g) ?? []).map(q => q.length))
  return '"'.repeat(Math.max(3, longest + 1))
}

/**
 * A story as JSON inside a raw string literal, parsed once, the first time
 * the story is read.
 */
export function storyCs(story) {
  const json = JSON.stringify(
    {
      id: story.id,
      name: story.name,
      summary: story.summary,
      preview: story.preview,
      examples: story.examples.map(({ title, note, scene }) => ({
        title,
        ...(note ? { note } : {}),
        demo: scene,
      })),
    },
    null,
    2
  )
  const quotes = fence(json)
  const name = pascal(story.id)
  return `// Generated by tools/codegen from
// packages/js/dazzui-react/example/src/stories/${story.id}.tsx. Do not edit.

namespace DazzUI.Example;

static partial class Stories
{
    private static Story? ${camel(story.id)}Story;

    public static Story ${name} => ${camel(story.id)}Story ??= Story.Parse(
        ${quotes}
${json
  .split('\n')
  .map(line => `        ${line}`)
  .join('\n')}
        ${quotes});
}
`
}

const camel = id => pascal(id).replace(/^./, letter => letter.toLowerCase())

/** Every story, by name — the React example's `stories/index.ts`. */
export function storiesIndexCs(stories) {
  return `${header}
namespace DazzUI.Example;

/// <summary>Every component the example shows, by name.</summary>
static partial class Stories
{
    private static IReadOnlyList<Story>? all;

    public static IReadOnlyList<Story> All => all ??=
    [
${stories.map(story => `        ${pascal(story.id)},`).join('\n')}
    ];

    public static Story? Find(string? id) => All.FirstOrDefault(story => story.Id == id);

    /// <summary>The components a query leaves.</summary>
    public static IReadOnlyList<Story> Matching(string query = "")
    {
        var needle = query.Trim();
        return needle.Length == 0
            ? All
            : All.Where(story =>
                story.Name.Contains(needle, StringComparison.OrdinalIgnoreCase) ||
                story.Summary.Contains(needle, StringComparison.OrdinalIgnoreCase)).ToArray();
    }
}
`
}

/** The glyphs the example window draws itself, beside the stories' own. */
const SHELL_GLYPHS = [
  'Home20Regular',
  'PanelLeft20Regular',
  'PanelRight20Regular',
  'WeatherMoon20Regular',
  'WeatherSunny20Regular',
]

/**
 * A React glyph's name as FluentIcons.WinUI spells it: `Settings20Regular`
 * is the `Settings` icon, `Regular` variant, drawn on the 20px grid — the
 * one grid the kit's resizable icon is drawn on.
 */
export function glyphOf(name) {
  const match = name.match(/^([A-Z][A-Za-z0-9]*?)(\d+)(Regular|Filled)$/)
  if (!match) throw new Error(`Not a Fluent glyph name: ${name}`)
  const [, icon, size, variant] = match
  if (size !== '20')
    throw new Error(`${name}: WinUI draws Fluent glyphs on the 20px grid`)
  return { icon, variant }
}

export function glyphsCs(stories) {
  const names = new Set(SHELL_GLYPHS)
  const visit = value => {
    if (Array.isArray(value)) return value.forEach(visit)
    if (!value || typeof value !== 'object') return
    if (typeof value.$icon === 'string') names.add(value.$icon)
    Object.values(value).forEach(visit)
  }
  visit(stories)
  return `${header}using FluentIcons.Common;

namespace DazzUI.Example;

/// <summary>The Fluent glyphs the stories and the window name, by their React name.</summary>
public static class Glyphs
{
    public static readonly IReadOnlyDictionary<string, (Glyph Glyph, IconVariant Variant)> All =
        new Dictionary<string, (Glyph, IconVariant)>
        {
${[...names]
  .sort()
  .map(name => {
    const { icon, variant } = glyphOf(name)
    return `            [${JSON.stringify(name)}] = (Glyph.${icon}, IconVariant.${variant}),`
  })
  .join('\n')}
        };

    /// <summary>A glyph, drawn at <paramref name="size"/>.</summary>
    public static Icon Draw(string name, double? size = null)
    {
        if (!All.TryGetValue(name, out var glyph)) throw new KeyNotFoundException($"No glyph named {name}");
        return new Icon { Glyph = glyph.Glyph, GlyphVariant = glyph.Variant, GlyphSize = size };
    }
}
`
}

/** The themes, as the React window groups them. */
export function themesCs(groups, names) {
  const ids = groups.flatMap(group =>
    group.families.flatMap(family => [
      `${family.value}-light`,
      `${family.value}-dark`,
    ])
  )
  for (const id of ids)
    if (!names.includes(id))
      throw new Error(`The WinUI package has no theme named ${id}`)
  return `${header}
namespace DazzUI.Example;

/// <summary>A theme: a family, in one of its two halves.</summary>
public sealed record ThemeChoice(string Family, bool Dark = false)
{
    /// <summary>The theme's name, as the web's <c>data-theme</c> writes it.</summary>
    public string Id => $"{Family}-{(Dark ? "dark" : "light")}";

    public Theme Theme => new(Id);

    public static ThemeChoice Default { get; } = new("studio");
}

/// <summary>A theme family: one name, in light and in dark.</summary>
public sealed record ThemeFamily(string Value, string Title);

public sealed record ThemeFamilyGroup(string Title, IReadOnlyList<ThemeFamily> Families);

public static class Themes
{
    public static readonly IReadOnlyList<ThemeFamilyGroup> Groups =
    [
${groups
  .map(
    group => `        new(${JSON.stringify(group.title)},
        [
${group.families.map(family => `            new(${JSON.stringify(family.value)}, ${JSON.stringify(family.title)}),`).join('\n')}
        ]),`
  )
  .join('\n')}
    ];
}
`
}
