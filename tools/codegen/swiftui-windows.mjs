// Package the Fluent glyphs used by the Windows, Linux and Web Swift builds.
// Artwork comes from the same official Fluent React package as other ports.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { glyphSvg } from './gpui.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const base = path.join(root, 'packages/swift/DazzUI')
const names = new Set()
function scan(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) scan(file)
    else if (file.endsWith('.swift')) {
      for (const match of fs
        .readFileSync(file, 'utf8')
        .matchAll(/\.([a-z]\w*\d+(?:Regular|Filled))\b/g))
        names.add(match[1])
    }
  }
}
scan(path.join(base, 'Sources'))
scan(path.join(base, 'Example/Sources'))
const output = path.join(base, 'Windows/FluentIcons')
const check = process.argv.includes('--check')
function write(file, contents) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents) {
      console.error(`Stale generated asset: ${path.relative(root, file)}`)
      process.exitCode = 1
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, contents)
  }
}
for (const name of [...names].sort()) {
  write(
    path.join(output, 'Resources', `${name}.svg`),
    glyphSvg(root, name[0].toUpperCase() + name.slice(1))
  )
}
write(
  path.join(output, 'FluentIcon.swift'),
  `// Generated by tools/codegen/swiftui-windows.mjs. Do not edit.
import SwiftUI
import Foundation

public enum FluentIcon: String, CaseIterable, Sendable {
${[...names]
  .sort()
  .map(name => `  case ${name}`)
  .join('\n')}
}
public extension Image {
  init(fluent icon: FluentIcon) {
    #if os(WASI) || SWIFTUI_PORT_HARMONY
      self.init("fluent/\\(icon.rawValue).svg")
    #else
      self.init(icon.rawValue, bundle: .module)
    #endif
  }
}
`
)
console.log(
  `${check ? 'Checked' : 'Packaged'} ${names.size} Fluent glyphs for SwiftUI on Windows.`
)
