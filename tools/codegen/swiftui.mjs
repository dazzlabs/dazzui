import { SUPPORT as FLUTTER_SUPPORT } from './flutter.mjs'
import { gaps } from './support.mjs'

/*
 * The SwiftUI example's generated sources: the stories as data, the glyphs
 * they name, and the themes the window offers.
 *
 * `SUPPORT` is the contract with the SwiftUI scene interpreter
 * (`Example/Sources/Example/Lib/Mapping.swift`), as Flutter's is with its
 * own. The two draw the same components today, so the list starts as
 * Flutter's; it is SwiftUI's to narrow or widen.
 */
export const SUPPORT = structuredClone(FLUTTER_SUPPORT)
// These mappings still accept the original preference slots only.
SUPPORT.PreferenceGroup = ['title', 'description', '#children']
SUPPORT.PreferenceRow = ['title', 'subtitle', 'onOpen', '#children']
SUPPORT.PreferenceSection = ['label', 'footer', '#children']

/** Every component and prop a story sets that SwiftUI does not draw. */
export const unsupported = stories => gaps(stories, SUPPORT, 'SwiftUI')

const header =
  '// Generated by tools/codegen from the React example. Do not edit.\n'

const SWIFT_KEYWORDS = new Set(
  'associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private protocol public rethrows static struct subscript typealias var break case continue default defer do else fallthrough for guard if in repeat return switch where while as catch false is nil super self Self throw throws true try'.split(
    ' '
  )
)

const pascal = id =>
  id.replace(/(^|-)([a-z0-9])/g, (_, __, letter) => letter.toUpperCase())
const camel = id => pascal(id).replace(/^./, letter => letter.toLowerCase())
/** A story's member on `Stories`, fenced when it is a Swift keyword. */
const member = id =>
  SWIFT_KEYWORDS.has(camel(id)) ? `\`${camel(id)}\`` : camel(id)

/** A story's file name on SwiftUI: the React file's, in Swift's casing. */
export const storyFile = id => `${pascal(id)}.swift`

/**
 * A story as JSON inside a raw string, decoded once at launch. A literal of
 * nested Swift values this size would take the type checker longer than
 * the whole app takes to build.
 */
export function storySwift(story) {
  const json = JSON.stringify(
    {
      id: story.id,
      name: story.name,
      summary: story.summary,
      preview: story.preview,
      examples: story.examples.map(({ title, note, scene }) => ({
        title,
        ...(note ? { note } : {}),
        demo: scene,
      })),
    },
    null,
    2
  )
  if (json.includes('"""#'))
    throw new Error(`${story.id}: cannot fence its JSON`)
  return `// Generated by tools/codegen from
// packages/js/dazzui/example/src/stories/${story.id}.tsx. Do not edit.

extension Stories {
  static let ${member(story.id)} = Story(
    #"""
${json
  .split('\n')
  .map(line => `    ${line}`)
  .join('\n')}
    """#
  )
}
`
}

/** Every story, by name — the React example's `stories/index.ts`. */
export function storiesIndexSwift(stories) {
  return `${header}
/// Every component the example shows, by name.
enum Stories {
  static let all: [Story] = [
${stories.map(story => `    ${member(story.id)},`).join('\n')}
  ]

  static func story(_ id: String?) -> Story? {
    all.first { $0.id == id }
  }

  /// The components a query leaves.
  static func matching(_ query: String = "") -> [Story] {
    let needle = query.trimmingCharacters(in: .whitespaces).lowercased()
    guard !needle.isEmpty else { return all }
    return all.filter {
      $0.name.lowercased().contains(needle) || $0.summary.lowercased().contains(needle)
    }
  }
}
`
}

export function glyphsSwift(stories) {
  const names = new Set()
  const visit = value => {
    if (Array.isArray(value)) return value.forEach(visit)
    if (!value || typeof value !== 'object') return
    if (typeof value.$icon === 'string') names.add(value.$icon)
    Object.values(value).forEach(visit)
  }
  visit(stories)
  const swift = name => name.replace(/^./, letter => letter.toLowerCase())
  return `${header}import FluentIcons

/// The Fluent glyphs the stories name, by their React name.
let glyphs: [String: FluentIcon] = [
${[...names]
  .sort()
  .map(name => `  ${JSON.stringify(name)}: .${swift(name)},`)
  .join('\n')}
]
`
}

/** The themes, as the React window groups them. */
export function themesSwift(groups, names) {
  const ids = groups.flatMap(group =>
    group.families.flatMap(family => [
      `${family.value}-light`,
      `${family.value}-dark`,
    ])
  )
  for (const id of ids)
    if (!names.includes(`"${id}"`))
      throw new Error(`The SwiftUI package has no theme named ${id}`)
  return `${header}import DazzUI

/// A theme: a family, in one of its two halves.
struct ThemeChoice: Hashable {
  var family: String
  var dark = false

  /// The theme's name, as the web's \`data-theme\` writes it.
  var id: String { "\\(family)-\\(dark ? "dark" : "light")" }

  var name: ThemeName { ThemeName(rawValue: id) ?? .studioLight }
}

let defaultTheme = ThemeChoice(family: "studio")

/// A theme family: one name, in light and in dark.
struct ThemeFamily: Hashable {
  let value: String
  let title: String
}

struct ThemeFamilyGroup {
  let title: String
  let families: [ThemeFamily]
}

let themeFamilyGroups: [ThemeFamilyGroup] = [
${groups
  .map(
    group => `  ThemeFamilyGroup(title: ${JSON.stringify(group.title)}, families: [
${group.families.map(family => `    ThemeFamily(value: ${JSON.stringify(family.value)}, title: ${JSON.stringify(family.title)}),`).join('\n')}
  ]),`
  )
  .join('\n')}
]
`
}
