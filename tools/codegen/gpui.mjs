import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { SUPPORT as FLUTTER_SUPPORT } from './flutter.mjs'
import { gaps } from './support.mjs'

/*
 * The GPUI example's generated sources: the stories as data, the glyphs
 * they name, and the themes the window offers — and one file in the kit
 * itself, the glyphs its components draw.
 *
 * `SUPPORT` is the contract with the GPUI scene interpreter
 * (`packages/rust/dazzui/example/src/lib/mapping.rs`), as Flutter's is with
 * its own.
 */
export const SUPPORT = structuredClone(FLUTTER_SUPPORT)
delete SUPPORT.PreferenceThemeSwatches
SUPPORT.FieldValue = ['size', 'mono', '#children']
SUPPORT.PreferenceGroup = ['title', 'description', '#children']
SUPPORT.PreferenceRow = ['title', 'subtitle', 'onOpen', '#children']
SUPPORT.PreferenceSection = ['label', 'footer', '#children']

/** Every component and prop a story sets that GPUI does not draw. */
export const unsupported = stories => gaps(stories, SUPPORT, 'GPUI')

const header =
  '// Generated by tools/codegen from the React example. Do not edit.\n'

const RUST_KEYWORDS = new Set(
  'as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub ref return self static struct super trait true type unsafe use where while'.split(
    ' '
  )
)

const snake = id => id.replace(/-/g, '_')
/** A story's module: the React file's name, in Rust's casing. */
const module = id =>
  RUST_KEYWORDS.has(snake(id)) ? `r#${snake(id)}` : snake(id)

/** A story's file name on GPUI. */
export const storyFile = id => `${snake(id)}.rs`

/** A string as a raw literal with enough hashes to fence it. */
function raw(text) {
  let hashes = '#'
  while (text.includes(`"${hashes}`)) hashes += '#'
  return `r${hashes}"${text}"${hashes}`
}

/**
 * A story as JSON inside a raw string, parsed once at launch — the SwiftUI
 * example's arrangement, for the same reason: a literal tree of Rust values
 * this size would cost the compiler more than the data is worth.
 */
export function storyRs(story) {
  const json = JSON.stringify(
    {
      id: story.id,
      name: story.name,
      summary: story.summary,
      preview: story.preview,
      examples: story.examples.map(({ title, note, scene }) => ({
        title,
        ...(note ? { note } : {}),
        demo: scene,
      })),
    },
    null,
    2
  )
  return `// Generated by tools/codegen from
// packages/js/dazzui/example/src/stories/${story.id}.tsx. Do not edit.

pub const STORY: &str = ${raw(`\n${json}\n`)};
`
}

/** Every story, in the order the React example lists them. */
export function storiesIndexRs(stories) {
  return `${header}
${stories.map(story => `mod ${module(story.id)};`).join('\n')}

/// Every story's JSON, in the order the React example lists them.
pub static SOURCES: &[&str] = &[
${stories.map(story => `    ${module(story.id)}::STORY,`).join('\n')}
];
`
}

/* Glyphs ----------------------------------------------------------------- */

const exampleRequire = root =>
  createRequire(path.join(root, 'packages/js/dazzui/example/package.json'))

let renderer
/**
 * A Fluent glyph's SVG, exactly as React renders it: the icon component is
 * rendered to markup and its paths kept, so GPUI draws the same outline the
 * web does rather than a second source's idea of it.
 */
export function glyphSvg(root, name) {
  renderer ??= (() => {
    const require = exampleRequire(root)
    const React = require('react')
    const { renderToStaticMarkup } = require('react-dom/server')
    const icons = require('@fluentui/react-icons')
    return glyph => {
      if (!icons[glyph]) throw new Error(`No Fluent glyph named ${glyph}`)
      return renderToStaticMarkup(React.createElement(icons[glyph]))
    }
  })()
  const markup = renderer(name)
  const grid = Number(/viewBox="0 0 (\d+) \1"/.exec(markup)?.[1])
  const paths = [...markup.matchAll(/ d="([^"]+)"/g)].map(match => match[1])
  if (!grid || !paths.length) throw new Error(`Unreadable glyph ${name}`)
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${grid} ${grid}">${paths
    .map(d => `<path fill="#000" d="${d}"/>`)
    .join('')}</svg>`
}

/** `ChevronDown12Regular` → `CHEVRON_DOWN_12_REGULAR`. */
const constant = name =>
  name
    .replace(/([a-z])([A-Z0-9])/g, '$1_$2')
    .replace(/([0-9])([A-Z])/g, '$1_$2')
    .toUpperCase()

/** The Fluent glyphs the `.tsx` files in a directory import. */
function importedGlyphs(dir) {
  const names = new Set()
  for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.tsx'))) {
    const source = fs.readFileSync(path.join(dir, file), 'utf8')
    for (const match of source.matchAll(
      /import\s*\{([^}]+)\}\s*from\s*'@fluentui\/react-icons'/g
    ))
      for (const item of match[1].split(','))
        if (item.trim()) names.add(item.trim().split(/\s+as\s+/)[0])
  }
  return [...names].sort()
}

/** The glyphs the kit's own components import, read off their sources. */
export const kitGlyphNames = root =>
  importedGlyphs(path.join(root, 'packages/js/dazzui/src/components'))

/**
 * The kit's glyphs, embedded: a path constant per glyph for a component to
 * draw, and the table `dazzui::Assets` serves them from.
 */
export function kitGlyphsRs(root, names = kitGlyphNames(root)) {
  return `${header}//! The Fluent glyphs the kit's components draw, as React imports them.

${names.map(name => `pub const ${constant(name)}: &str = "dazzui/${name}.svg";`).join('\n')}

/// Every glyph above, by its asset path, as SVG.
pub(crate) static SVGS: &[(&str, &str)] = &[
${names.map(name => `    (${constant(name)}, ${raw(glyphSvg(root, name))}),`).join('\n')}
];
`
}

/**
 * The Fluent glyphs the example draws, by their React name: those the
 * stories name, and those the React window imports, since the GPUI window
 * is drawn to the same glyphs.
 */
export function glyphsRs(root, stories) {
  const svgs = glyphSvgs(root, stories)
  return `${header}
/// The Fluent glyphs the example draws, by their React name, as SVG.
pub static GLYPHS: &[(&str, &str)] = &[
${[...svgs].map(([name, svg]) => `    (${JSON.stringify(name)}, ${raw(svg)}),`).join('\n')}
];
`
}

export function glyphSvgs(root, stories) {
  const names = new Set()
  const visit = value => {
    if (Array.isArray(value)) return value.forEach(visit)
    if (!value || typeof value !== 'object') return
    if (typeof value.$icon === 'string') names.add(value.$icon)
    Object.values(value).forEach(visit)
  }
  visit(stories)
  const window = path.join(root, 'packages/js/dazzui/example/src/components')
  for (const name of importedGlyphs(window)) names.add(name)
  return new Map([...names].sort().map(name => [name, glyphSvg(root, name)]))
}

/* Themes ----------------------------------------------------------------- */

/** The themes, as the React window groups them. */
export function themesRs(groups, generated) {
  for (const group of groups)
    for (const family of group.families)
      for (const half of ['light', 'dark'])
        if (!generated.includes(`name: "${family.value}-${half}"`))
          throw new Error(
            `The GPUI package has no theme named ${family.value}-${half}`
          )
  return `${header}
/// A theme family: one name, in light and in dark.
pub struct ThemeFamily {
    pub value: &'static str,
    pub title: &'static str,
}

pub struct ThemeFamilyGroup {
    pub title: &'static str,
    pub families: &'static [ThemeFamily],
}

pub static THEME_FAMILY_GROUPS: &[ThemeFamilyGroup] = &[
${groups
  .map(
    group => `    ThemeFamilyGroup {
        title: ${JSON.stringify(group.title)},
        families: &[
${group.families.map(family => `            ThemeFamily { value: ${JSON.stringify(family.value)}, title: ${JSON.stringify(family.title)} },`).join('\n')}
        ],
    },`
  )
  .join('\n')}
];
`
}
