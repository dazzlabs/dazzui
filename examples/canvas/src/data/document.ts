import type { Doc, Shape } from '../lib/scene'

/**
 * The drawing the prototype opens at.
 *
 * It draws this repository rather than a made-up product: the first page is
 * the token pipeline `AGENTS.md` describes, step for step, and the second is a
 * cover for the design system the canvas is built out of. A prototype that
 * invents its content has to invent its labels too, and invented labels are
 * the first thing that reads as a mock.
 *
 * Coordinates are scene units, counted from each page's own origin. Pages do
 * not share a space — opening one frames it — so both start at the corner.
 */
type Draft = Pick<
  Shape,
  'id' | 'kind' | 'name' | 'x' | 'y' | 'width' | 'height'
> &
  Partial<Shape>

function shape(draft: Draft): Shape {
  return {
    tint: 'neutral',
    variant: 'tinted',
    radius: 0,
    size: 14,
    opacity: 100,
    text: '',
    locked: false,
    hidden: false,
    ...draft,
  }
}

