import { resolveThemes, themeModes } from './resolve.mjs'

/**
 * Terrazzo plugin to generate the GPUI crate's token source.
 *
 * Rust has no cascade either, so a theme is a finished value rather than a
 * block of overrides — but it has something Dart and Swift lack: struct
 * update syntax in a `const`. Every theme is therefore resolved whole here,
 * by the same walk WinUI's snapshot takes, and written as only the fields
 * that differ from Studio Light's:
 *
 *     pub const STUDIO_DARK: ThemeTokens = ThemeTokens {
 *         color_canvas: Color(0x0f0f12ff),
 *         ..STUDIO_LIGHT
 *     };
 *
 * so the diff a token change makes is the diff it reads as, and nothing is
 * derived at run time. The one thing left open is the tint: a recipe cell
 * that picks a shade off whichever ramp the control is tinted with stays a
 * `Paint::Shade`, resolved against that ramp where it is drawn, exactly as
 * the CSS leaves `--tint-600` to `[data-tint]`.
 *
 * A field is named after its token with the separators folded into
 * underscores — `control.medium.padding.inline` is
 * `control_medium_padding_inline`, `labelStrong` is `label_strong` — so it
 * reads as the custom property the React stylesheet reads. Three kinds of
 * group collapse into one field: a ramp's eleven steps (`color_primary`), a
 * recipe cell's shade, alpha and colour (`control_color_filled_surface_hovered`),
 * and the same pair outside the table (`focus_ring`, `dialog_scrim`).
 */
export default function gpuiPlugin({ modeSelectors = [] } = {}) {
  return {
    name: '@dazzlabs/dazzui-ds-plugin-gpui',
    build({ tokens, outputFile }) {
      outputFile('gpui/theme_tokens.rs', generate(tokens, modeSelectors))
    },
  }
}

const HEADER = `// Design tokens generated from Terrazzo
// DO NOT EDIT - This file is auto-generated by ds/plugins/gpui.mjs`

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
const RAMP_STEP = /^(color\.[a-z]+)\.(\d+)$/
const PAINT_LEAF = /^(.+)\.(shade|alpha|color)$/

export function generate(tokens, modeSelectors) {
  const themes = resolveThemes(tokens, modeSelectors)
  const modes = themeModes(modeSelectors)
  const fields = describe(themes['studio-light'])
  const values = Object.fromEntries(
    Object.entries(themes).map(([name, snapshot]) => [
      name,
      Object.fromEntries(
        fields.map(field => [field.name, field.emit(snapshot)])
      ),
    ])
  )

  const lines = [
    HEADER,
    '',
    '#![allow(clippy::all)]',
    '',
    'use crate::tokens::*;',
    '',
    '/// Every semantic and component token, resolved for one theme.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct ThemeTokens {',
    ...fields.map(field => `    pub ${field.name}: ${field.type},`),
    '}',
    '',
  ]

  const base = values['studio-light']
  for (const [name, fieldValues] of Object.entries(values)) {
    lines.push(`pub const ${constName(name)}: ThemeTokens = ThemeTokens {`)
    for (const field of fields) {
      const value = fieldValues[field.name]
      if (name === 'studio-light' || value !== base[field.name]) {
        lines.push(`    ${field.name}: ${value},`)
      }
    }
    if (name !== 'studio-light') lines.push('    ..STUDIO_LIGHT')
    lines.push('};', '')
  }

  lines.push(
    '/// Every theme, by the name React selects it with (`data-theme`).',
    'pub static THEMES: &[ThemeEntry] = &['
  )
  for (const name of Object.keys(values)) {
    const dark = modes.get(name).includes('dark')
    lines.push(
      `    ThemeEntry { name: ${JSON.stringify(name)}, dark: ${dark}, tokens: &${constName(name)} },`
    )
  }
  lines.push('];', '')
  return lines.join('\n')
}

/** The struct's fields, in token order, each knowing how to write itself. */
function describe(snapshot) {
  const ids = Object.keys(snapshot)
  const fields = []
  const taken = new Set()

  for (const id of ids) {
    const ramp = RAMP_STEP.exec(id)
    if (ramp) {
      const group = ramp[1]
      if (taken.has(group)) continue
      taken.add(group)
      for (const shade of SHADES) {
        if (!(`${group}.${shade}` in snapshot)) {
          throw new Error(`Ramp ${group} has no step ${shade}`)
        }
      }
      fields.push({
        name: fieldName(group),
        type: 'Ramp',
        emit: s =>
          `Ramp([${SHADES.map(shade => color(s[`${group}.${shade}`])).join(', ')}])`,
      })
      continue
    }

    const leaf = PAINT_LEAF.exec(id)
    if (
      leaf &&
      (`${leaf[1]}.shade` in snapshot || `${leaf[1]}.color` in snapshot)
    ) {
      const group = leaf[1]
      if (taken.has(group)) continue
      taken.add(group)
      fields.push({
        name: fieldName(group),
        type: 'Paint',
        emit: s => {
          const alpha = number(s[`${group}.alpha`] ?? 1)
          if (`${group}.shade` in s) {
            return `Paint::Shade(${s[`${group}.shade`]}, ${alpha})`
          }
          return `Paint::Color(${color(s[`${group}.color`])}, ${alpha})`
        },
      })
      continue
    }

    fields.push(scalar(id, snapshot[id]))
  }
  return fields
}

function scalar(id, value) {
  const name = fieldName(id)
  if (isColor(value)) return { name, type: 'Color', emit: s => color(s[id]) }
  if (typeof value === 'number') {
    return { name, type: 'f32', emit: s => number(s[id]) }
  }
  if (value?.unit === 'ms') {
    return { name, type: 'f32', emit: s => number(s[id].value) }
  }
  if (value?.unit === 'px' || value?.unit === 'rem') {
    return { name, type: 'f32', emit: s => number(px(s[id])) }
  }
  if (id === 'motion.easing') {
    return {
      name,
      type: '[f32; 4]',
      emit: s => `[${s[id].map(number).join(', ')}]`,
    }
  }
  if (value?.fontFamily) {
    return { name, type: 'TypeStyle', emit: s => typeStyle(s[id]) }
  }
  if (Array.isArray(value) && value[0]?.offsetX) {
    return {
      name,
      type: "&'static [Shadow]",
      emit: s => `&[${s[id].map(shadow).join(', ')}]`,
    }
  }
  throw new Error(`No Rust type for ${id}: ${JSON.stringify(value)}`)
}

function typeStyle(value) {
  const face = value.fontFamily.includes('SF Pro Display')
    ? 'Face::Display'
    : value.fontFamily.some(f => /mono/i.test(f))
      ? 'Face::Mono'
      : 'Face::Text'
  return (
    `TypeStyle { face: ${face}, size: ${number(px(value.fontSize))}, ` +
    `line_height: ${number(px(value.lineHeight))}, weight: ${value.fontWeight} }`
  )
}

function shadow(layer) {
  if (layer.inset) throw new Error('An inset shadow has no GPUI drawing')
  return (
    `Shadow { color: ${color(layer.color)}, x: ${number(px(layer.offsetX))}, ` +
    `y: ${number(px(layer.offsetY))}, blur: ${number(px(layer.blur))}, ` +
    `spread: ${number(px(layer.spread))} }`
  )
}

const isColor = value =>
  Array.isArray(value) &&
  value.length === 4 &&
  value.every(v => Number.isInteger(v) && v >= 0 && v <= 255)

/** `[a, r, g, b]` bytes as `Color(0xrrggbbaa)`, the order `gpui::rgba` reads. */
function color([a, r, g, b]) {
  const hex = [r, g, b, a].map(v => v.toString(16).padStart(2, '0')).join('')
  return `Color(0x${hex})`
}

function px(dimension) {
  if (dimension.unit === 'px') return dimension.value
  if (dimension.unit === 'rem') return dimension.value * 16
  throw new Error(`Unsupported unit: ${dimension.unit}`)
}

function number(value) {
  const text = String(Math.round(value * 1e6) / 1e6)
  return text.includes('.') || text.includes('e') ? text : `${text}.0`
}

function fieldName(id) {
  return id
    .replace(/([a-z])([A-Z])/g, '$1_$2')
    .replace(/[.-]/g, '_')
    .toLowerCase()
}

function constName(theme) {
  return theme.replace(/-/g, '_').toUpperCase()
}
