import { buildCatalog } from './catalog.mjs'

/**
 * Terrazzo plugin generating the typed web theme catalog (`themes.ts`).
 *
 * Applications consume these generated types and metadata instead of
 * hand-maintaining lists of DazzUI, desktop, application and Omarchy themes.
 */
export function generateThemesTS(modeSelectors = []) {
  const { groups, families, themes } = buildCatalog(modeSelectors)
  const drawn = families
    .filter(entry => entry.group === 'drawn')
    .map(entry => entry.family)

  const quote = value =>
    `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  const keyOf = key =>
    /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : quote(key)

  const familyMetaEntries = families
    .map(
      entry =>
        `  ${keyOf(entry.family)}: {\n` +
        `    family: ${quote(entry.family)},\n` +
        `    title: ${quote(entry.title)},\n` +
        `    group: ${quote(entry.group)},\n` +
        `    light: ${quote(entry.light)},\n` +
        `    dark: ${quote(entry.dark)},\n` +
        `  },`
    )
    .join('\n')

  const themeMetaEntries = themes
    .map(
      entry =>
        `  ${keyOf(entry.name)}: {\n` +
        `    name: ${quote(entry.name)},\n` +
        `    family: ${quote(entry.family)},\n` +
        `    appearance: ${quote(entry.appearance)},\n` +
        `    group: ${quote(entry.group)},\n` +
        `    title: ${quote(entry.title)},\n` +
        `    familyTitle: ${quote(entry.familyTitle)},\n` +
        `    isDefault: ${entry.isDefault},\n` +
        `  },`
    )
    .join('\n')

  const formatFamiliesArray = list => {
    const inline = `    families: [${list.map(quote).join(', ')}],`
    if (inline.length <= 80) return inline
    return (
      `    families: [\n` +
      `${list.map(family => `      ${quote(family)},`).join('\n')}\n` +
      `    ],`
    )
  }

  const groupEntries = groups
    .map(
      group =>
        `  {\n` +
        `    id: ${quote(group.id)},\n` +
        `    title: ${quote(group.title)},\n` +
        `${formatFamiliesArray(group.families)}\n` +
        `  },`
    )
    .join('\n')

  return `// Generated by ds/plugins/themes-ts.mjs. Do not edit. Run pnpm tokens.

export type Appearance = 'light' | 'dark'

export type ThemeGroup = 'drawn' | 'desktops' | 'applications' | 'omarchy'

export const DRAWN_THEME_FAMILIES = [
${drawn.map(family => `  ${quote(family)},`).join('\n')}
] as const

export type DrawnThemeFamily = (typeof DRAWN_THEME_FAMILIES)[number]

export const THEME_FAMILIES = [
${families.map(entry => `  ${quote(entry.family)},`).join('\n')}
] as const

export type ThemeFamily = (typeof THEME_FAMILIES)[number]

export const THEMES = [
${themes.map(entry => `  ${quote(entry.name)},`).join('\n')}
] as const

export type ThemeName = (typeof THEMES)[number]

export const DEFAULT_THEME_FAMILY: ThemeFamily = 'bright'
export const DEFAULT_THEME: ThemeName = 'bright-light'

export interface ThemeFamilyMeta {
  readonly family: ThemeFamily
  readonly title: string
  readonly group: ThemeGroup
  readonly light: ThemeName
  readonly dark: ThemeName
}

export interface ThemeMeta {
  readonly name: ThemeName
  readonly family: ThemeFamily
  readonly appearance: Appearance
  readonly group: ThemeGroup
  readonly title: string
  readonly familyTitle: string
  readonly isDefault: boolean
}

export interface ThemeGroupInfo {
  readonly id: ThemeGroup
  readonly title: string
  readonly families: readonly ThemeFamily[]
}

export const THEME_FAMILY_META: Record<ThemeFamily, ThemeFamilyMeta> = {
${familyMetaEntries}
}

export const THEME_META: Readonly<Record<ThemeName, ThemeMeta>> = {
${themeMetaEntries}
}

export const THEME_GROUPS: readonly ThemeGroupInfo[] = [
${groupEntries}
]

export function isThemeName(value: string): value is ThemeName {
  return Object.prototype.hasOwnProperty.call(THEME_META, value)
}

export function isThemeFamily(value: string): value is ThemeFamily {
  return Object.prototype.hasOwnProperty.call(THEME_FAMILY_META, value)
}

export function resolveThemeName(
  family: ThemeFamily,
  dark: boolean | Appearance
): ThemeName {
  const isDark = typeof dark === 'boolean' ? dark : dark === 'dark'
  const meta = THEME_FAMILY_META[family]
  return isDark ? meta.dark : meta.light
}
`
}

export default function themesTSPlugin({ modeSelectors = [] } = {}) {
  return {
    name: '@dazzlabs/dazzui-ds-plugin-themes-ts',
    build({ outputFile }) {
      outputFile('themes.ts', generateThemesTS(modeSelectors))
    },
  }
}
