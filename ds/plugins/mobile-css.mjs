import { rgba, roles } from './compose.mjs'

/**
 * Terrazzo plugin to generate the React mobile package's colour sheet.
 *
 * `@dazzlabs/dazzui-mobile` is the web counterpart of `DazzMobileUI`
 * and `dazzui-mobile`: ds colours over controls drawn as the OS draws them,
 * iOS's and Android's. Like those two it takes only colour from here —
 * geometry, type and motion are the platform's, transcribed in the package's
 * own `styles/ios.css` and `styles/android.css` — so this sheet carries the
 * semantic roles, the six accents at the shade `filled` picks,
 * and the Material roles the Compose plugin derives, under the same names
 * and from the same mapping, so an Android control drawn on the web is the
 * colour the Kotlin package makes it.
 *
 * A theme is a family plus an appearance, and the appearance follows the OS
 * unless the host says otherwise, as the two native packages do. The
 * selectors compose to that:
 *
 *   [data-family='frost']                          the light half
 *   [data-family='frost'][data-appearance='dark']  the dark half, chosen
 *   @media (prefers-color-scheme: dark)
 *     [data-family='frost']:not([data-appearance='light'])
 *                                                  the dark half, followed
 *
 * Nothing lands on `:root`: a page may carry the desktop token sheet as
 * well — the mobile example's window is drawn with `@dazzlabs/dazzui` — and
 * that sheet owns `:root` and `data-theme`. Every value here lives on the
 * element `MobileTheme` renders, which always carries `data-family`.
 */
export default function mobileCSSPlugin({ modeSelectors = [] } = {}) {
  return {
    name: '@dazzlabs/dazzui-ds-plugin-mobile-css',
    async build({ tokens, outputFile }) {
      const themes = collectThemes(modeSelectors)
      outputFile('mobile/mobile.css', renderSheet(tokens, themes))
      outputFile('mobile/families.ts', renderFamilies(themes))
    },
  }
}

/** Every theme by name, with the modes it applies, Bright Light first. */
export function collectThemes(modeSelectors) {
  const themes = new Map([['bright-light', []]])
  for (const { mode, selectors = [] } of modeSelectors) {
    for (const selector of selectors) {
      const name = /\[data-theme='([^']+)'\]/.exec(selector)?.[1]
      if (!name) continue
      if (!themes.has(name)) themes.set(name, [])
      themes.get(name).push(mode)
    }
  }
  return themes
}

const TINTS = ['primary', 'neutral', 'info', 'success', 'warning', 'danger']

export function renderSheet(tokens, themes) {
  const families = [
    ...new Set(
      [...themes.keys()].map(name => name.replace(/-(light|dark)$/, ''))
    ),
  ]
  for (const family of families) {
    for (const half of ['light', 'dark']) {
      if (!themes.has(`${family}-${half}`)) {
        throw new Error(
          `Mobile CSS needs ${family}-${half}: every family comes in a pair.`
        )
      }
    }
  }

  const block = (selectors, family, half, indent = '') => {
    const modes = themes.get(`${family}-${half}`)
    const lines = [`${indent}  color-scheme: ${half};`]
    for (const [name, value] of variables(tokens, modes)) {
      lines.push(`${indent}  ${name}: ${value};`)
    }
    const head = selectors.map(s => `${indent}${s}`).join(',\n')
    return `${head} {\n${lines.join('\n')}\n${indent}}`
  }

  const light = families.map(family =>
    block([`[data-family='${family}']`], family, 'light')
  )
  const chosen = families.map(family =>
    block([`[data-family='${family}'][data-appearance='dark']`], family, 'dark')
  )
  const followed = families.map(family =>
    block(
      [`[data-family='${family}']:not([data-appearance='light'])`],
      family,
      'dark',
      '  '
    )
  )

  return `${HEADER}

${light.join('\n\n')}

${chosen.join('\n\n')}

@media (prefers-color-scheme: dark) {
${followed.join('\n\n')}
}
`
}

const HEADER = `/* Generated by ds. Do not edit. Run pnpm tokens. */`

/** The custom properties one theme sets, in order. */
function variables(tokens, modes) {
  const value = id => {
    const token = tokens[id]
    if (!token) throw new Error(`Missing mobile colour input: ${id}`)
    let result = token.$value
    for (const mode of modes) {
      if (token.mode?.[mode]) result = token.mode[mode].$value
    }
    return result
  }
  const color = id => hex(rgba(value(id)))
  const out = []

  // The semantic roles: every single-colour token under `color.`.
  for (const id of Object.keys(tokens).sort()) {
    const match = /^color\.([a-z-]+)$/.exec(id)
    if (!match || tokens[id].$type !== 'color') continue
    out.push([`--color-${match[1]}`, color(id)])
  }
  // The accents: each ramp at the shade the filled action picks, which a
  // dark theme lifts. `DazzMobileUI` calls the primary one `accent`. The
  // ramps themselves stay out: a native control is drawn in one colour and
  // its states in alpha, so nothing here ever indexes a shade.
  const shade = value('control.color.filled.surface.normal.shade')
  out.push(['--color-accent', color(`color.primary.${shade}`)])
  for (const tint of TINTS) {
    if (tint === 'primary') continue
    out.push([`--color-accent-${tint}`, color(`color.${tint}.${shade}`)])
  }
  // The Material roles, from the Compose plugin's mapping.
  for (const [role, rgb] of Object.entries(roles(tokens, modes))) {
    out.push([`--m3-${kebab(role)}`, hex(rgb)])
  }
  return out
}

export function renderFamilies(themes) {
  const families = [
    ...new Set(
      [...themes.keys()].map(name => name.replace(/-(light|dark)$/, ''))
    ),
  ]
  return `// Generated by ds. Do not edit. Run pnpm tokens.

/**
 * The theme families the sheet carries, each in a light and a dark half —
 * the same list \`DazzMobileUI\` and \`dazzui-mobile\` hand their hosts.
 */
export const FAMILIES = [
${families.map(family => `  '${family}',`).join('\n')}
] as const

export type Family = (typeof FAMILIES)[number]
`
}

function hex(c) {
  const channel = v =>
    Math.round(Math.max(0, Math.min(1, v)) * 255)
      .toString(16)
      .padStart(2, '0')
  const rgb = c.slice(0, 3).map(channel).join('')
  const alpha = c[3] ?? 1
  return `#${rgb}${alpha >= 1 ? '' : channel(alpha)}`
}

function kebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}
