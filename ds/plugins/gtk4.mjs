import { resolveThemes } from './resolve.mjs'

export const TINTS = [
  'primary',
  'neutral',
  'info',
  'success',
  'warning',
  'danger',
]
export const VARIANTS = [
  'filled',
  'tinted',
  'outlined',
  'normal',
  'recessed',
  'plain',
]
export const STATES = ['normal', 'hovered', 'pressed', 'disabled']
const PARTS = ['surface', 'content', 'border']
const name = id =>
  id
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replaceAll('.', '-')
    .toLowerCase()
const px = d => {
  if (d.unit === 'px') return d.value
  if (d.unit === 'rem') return d.value * 16
  throw new Error(`Unsupported GTK dimension: ${JSON.stringify(d)}`)
}
export const color = ([a, r, g, b], alpha = 1) =>
  `rgba(${r}, ${g}, ${b}, ${Math.round((a / 255) * alpha * 1e6) / 1e6})`

/** Resolve the authored recipe, including literal colours and baked alpha. */
export function paint(snapshot, id, tint = 'primary') {
  const shade = snapshot[`${id}.shade`]
  const value =
    shade === undefined
      ? snapshot[`${id}.color`]
      : snapshot[`color.${tint}.${shade}`]
  if (!value) throw new Error(`Missing GTK paint: ${id} / ${tint}`)
  return color(value, snapshot[`${id}.alpha`] ?? 1)
}

function values(snapshot) {
  const result = new Map()
  for (const [id, value] of Object.entries(snapshot)) {
    if (
      id.startsWith('control.color.') ||
      /^(focus\.(ring|glow)|dialog\.scrim)\./.test(id)
    )
      continue
    const key = name(id)
    if (value?.unit)
      result.set(
        key,
        `${value.unit === 'ms' ? value.value : px(value)}${value.unit === 'ms' ? 'ms' : 'px'}`
      )
    else if (value?.fontFamily) {
      result.set(
        `${key}-font-family`,
        value.fontFamily.map(JSON.stringify).join(', ')
      )
      result.set(`${key}-font-size`, `${px(value.fontSize)}px`)
      result.set(`${key}-font-weight`, String(value.fontWeight))
      result.set(`${key}-line-height`, `${px(value.lineHeight)}px`)
    } else if (typeof value === 'number') result.set(key, String(value))
    else if (Array.isArray(value) && value[0]?.offsetX) {
      result.set(
        key,
        value
          .map(
            s =>
              `${s.inset ? 'inset ' : ''}${px(s.offsetX)}px ${px(s.offsetY)}px ${px(s.blur)}px ${px(s.spread)}px ${color(s.color)}`
          )
          .join(', ')
      )
    } else if (id === 'motion.easing')
      result.set(key, `cubic-bezier(${value.join(', ')})`)
    else if (Array.isArray(value) && value.length === 4)
      result.set(key, color(value))
    else throw new Error(`Unsupported GTK token: ${id}`)
  }
  for (const id of ['focus.ring', 'focus.glow', 'dialog.scrim'])
    result.set(name(id), paint(snapshot, id))
  for (const tint of TINTS) {
    for (const variant of VARIANTS) {
      for (const part of PARTS) {
        for (const state of STATES) {
          result.set(
            `recipe-${tint}-${variant}-${part}-${state}`,
            paint(snapshot, `control.color.${variant}.${part}.${state}`, tint)
          )
        }
      }
    }
  }
  return result
}

export function generateCSS(themes) {
  const blocks = ['/* Generated by ds/plugins/gtk4.mjs. Do not edit. */']
  for (const [theme, snapshot] of Object.entries(themes)) {
    const entries = values(snapshot)
    // The base is inherited by every scope; a nested theme resets all base
    // values before its overrides so it cannot inherit the outer palette.
    blocks.push(
      `.dz-theme-${theme} {\n${[...entries].map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}`
    )
  }
  for (const tint of TINTS) {
    blocks.push(
      `.dz-tint-${tint} {\n${[50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950].map(s => `  --tint-${s}: var(--color-${tint}-${s});`).join('\n')}\n${VARIANTS.flatMap(v => PARTS.flatMap(p => STATES.map(s => `  --recipe-${v}-${p}-${s}: var(--recipe-${tint}-${v}-${p}-${s});`))).join('\n')}\n}`
    )
  }
  for (const variant of VARIANTS) {
    blocks.push(
      `.dz-variant-${variant} {\n${PARTS.flatMap(p => STATES.map(s => `  --control-${p}-${s}: var(--recipe-${variant}-${p}-${s});`)).join('\n')}\n}`
    )
  }
  for (const size of ['tiny', 'small', 'medium', 'large']) {
    const bindings = {
      size: `control-${size}-size`,
      gap: `control-${size}-gap`,
      'icon-size': `control-${size}-icon-size`,
      radius: `control-${size}-radius`,
      'padding-block': `control-${size}-padding-block`,
      'padding-inline': `control-${size}-padding-inline`,
      'font-family': `control-${size}-content-font-family`,
      'font-size': `control-${size}-content-font-size`,
      'font-weight': `control-${size}-content-font-weight`,
      'line-height': `control-${size}-content-line-height`,
    }
    blocks.push(
      `.dz-size-${size} {\n${Object.entries(bindings)
        .map(([bound, source]) => `  --control-${bound}: var(--${source});`)
        .join('\n')}\n}`
    )
  }
  for (const [id, value] of Object.entries(themes['bright-light'])) {
    if (id.startsWith('spacing.') && value?.unit)
      blocks.push(
        `.dz-gap-${name(id.slice(8))} { border-spacing: var(--${name(id)}); }`
      )
    if (value?.fontFamily)
      blocks.push(
        `.dz-type-${name(id)} { font-family: var(--${name(id)}-font-family); font-size: var(--${name(id)}-font-size); font-weight: var(--${name(id)}-font-weight); line-height: var(--${name(id)}-line-height); }`
      )
  }
  return `${blocks.join('\n\n')}\n`
}

export default function gtk4Plugin({ modeSelectors = [] } = {}) {
  return {
    name: '@dazzlabs/dazzui-ds-plugin-gtk4',
    build({ tokens, outputFile }) {
      const themes = resolveThemes(tokens, modeSelectors)
      outputFile('gtk4/tokens.css', generateCSS(themes))
      outputFile(
        'gtk4/themes.rs',
        `// Generated by ds/plugins/gtk4.mjs. Do not edit.\npub const THEMES: &[&str] = &[\n${Object.keys(
          themes
        )
          .map(n => `  ${JSON.stringify(n)},`)
          .join('\n')}\n];\n`
      )
    },
  }
}
