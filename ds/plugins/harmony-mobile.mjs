import { resolveThemes } from './resolve.mjs'
import { color } from './harmony.mjs'

/** ArkUI owns geometry, type, motion and interaction; ds supplies colors. */
export function mobileColors(values) {
  const role = name => color(values[`color.${name}`])
  const recipe = (variant, part, tint = 'primary', state = 'normal') => {
    const id = `control.color.${variant}.${part}.${state}`
    const shade = values[`${id}.shade`]
    return color(
      shade === undefined
        ? values[`${id}.color`]
        : values[`color.${tint}.${shade}`],
      values[`${id}.alpha`] ?? 1
    )
  }
  const accent = recipe('filled', 'surface')
  const emphasis = recipe('plain', 'content')
  return {
    brand: accent,
    warning: recipe('filled', 'surface', 'warning'),
    alert: recipe('filled', 'surface', 'danger'),
    confirm: recipe('filled', 'surface', 'success'),
    fontPrimary: role('content'),
    fontSecondary: role('content-secondary'),
    fontTertiary: role('content-muted'),
    fontFourth: role('content-faint'),
    fontEmphasize: emphasis,
    fontOnPrimary: role('on-accent'),
    fontOnSecondary: role('on-accent'),
    fontOnTertiary: role('on-accent'),
    fontOnFourth: role('on-accent'),
    iconPrimary: role('content'),
    iconSecondary: role('content-secondary'),
    iconTertiary: role('content-muted'),
    iconFourth: role('border-muted'),
    iconEmphasize: emphasis,
    iconSubEmphasize: recipe('tinted', 'content'),
    iconOnPrimary: role('on-accent'),
    iconOnSecondary: role('on-accent'),
    iconOnTertiary: role('on-accent'),
    iconOnFourth: role('on-accent'),
    backgroundPrimary: role('surface'),
    backgroundSecondary: role('surface-column'),
    backgroundTertiary: role('surface-muted'),
    backgroundFourth: role('surface-overlay'),
    backgroundEmphasize: accent,
    compForegroundPrimary: role('content'),
    compBackgroundPrimary: role('surface-raised'),
    compBackgroundPrimaryTran: color(values['color.surface-raised'], 0),
    compBackgroundPrimaryContrary: role('on-accent'),
    compBackgroundGray: role('surface-sunken'),
    compBackgroundSecondary: role('surface-inset'),
    compBackgroundTertiary: role('surface-muted'),
    compBackgroundEmphasize: accent,
    compBackgroundNeutral: role('content'),
    compEmphasizeSecondary: recipe('tinted', 'surface'),
    compEmphasizeTertiary: recipe('plain', 'surface', 'primary', 'hovered'),
    compDivider: role('border'),
    compCommonContrary: role('on-accent'),
    compBackgroundFocus: accent,
    compFocusedPrimary: role('on-accent'),
    compFocusedSecondary: role('on-accent'),
    compFocusedTertiary: role('on-accent'),
    // State opacity, disabled treatment and transitions remain ArkUI's.
  }
}

export function mobileFamilies(themes) {
  return Object.keys(themes)
    .filter(name => name.endsWith('-light'))
    .map(name => name.slice(0, -6))
    .filter(family => themes[`${family}-dark`])
}

export function generateMobile(themes) {
  const families = mobileFamilies(themes)
  const pascal = family =>
    family
      .split('-')
      .map(word => word[0].toUpperCase() + word.slice(1))
      .join('')
  const cases = families.map(family => {
    const theme = {
      colors: mobileColors(themes[`${family}-light`]),
      darkColors: mobileColors(themes[`${family}-dark`]),
    }
    return `    case DazzThemeFamily.${pascal(family)}:\n      return ${JSON.stringify(theme, null, 2).replace(/\n/g, '\n      ')}`
  })
  return `// Generated by ds/plugins/harmony-mobile.mjs. Do not edit. Run pnpm tokens.
import { CustomTheme } from '@kit.ArkUI'

export enum DazzThemeFamily {
${families.map(family => `  ${pascal(family)} = '${family}'`).join(',\n')}
}

export const DAZZ_THEME_FAMILIES: DazzThemeFamily[] = [
${families.map(family => `  DazzThemeFamily.${pascal(family)}`).join(',\n')}
]

/** Fresh scopes never share mutable color objects. ArkUI chooses the appearance. */
export function dazzTheme(family: DazzThemeFamily = DazzThemeFamily.Studio): CustomTheme {
  switch (family) {
${cases.join('\n')}
    default:
      throw new Error('Unknown DazzUI mobile family: ' + family)
  }
}
`
}

export default function harmonyMobilePlugin({ modeSelectors = [] } = {}) {
  return {
    name: '@dazzlabs/dazzui-ds-plugin-harmony-mobile',
    build({ tokens, outputFile }) {
      outputFile(
        'harmony-mobile/DazzThemes.ets',
        generateMobile(resolveThemes(tokens, modeSelectors))
      )
    },
  }
}
