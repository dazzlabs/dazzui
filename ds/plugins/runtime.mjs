import { resolveThemes } from './resolve.mjs'

const durations = {
  TOAST_NOTICE_MS: 'toast.notice-duration',
  TOAST_ACTION_MS: 'toast.action-duration',
}

// These APIs run before there is a DOM node to read a scoped CSS variable.
// Only theme-invariant values may enter this generated runtime module.
export function generate(themes) {
  const entries = Object.entries(themes)
  if (!entries.length) throw new Error('Runtime tokens require a theme')
  const output = ['// Generated by ds/plugins/runtime.mjs. Do not edit.']
  for (const [name, id] of Object.entries(durations)) {
    const value = entries[0][1][id]
    if (
      value?.unit !== 'ms' ||
      !Number.isFinite(value.value) ||
      value.value < 0
    )
      throw new Error(`Invalid runtime duration: ${id}`)
    for (const [theme, tokens] of entries)
      if (tokens[id]?.unit !== value.unit || tokens[id]?.value !== value.value)
        throw new Error(`Runtime token must not vary by theme: ${id}/${theme}`)
    output.push(`export const ${name} = ${value.value}`)
  }
  return output.join('\n') + '\n'
}

export default function runtimePlugin({ modeSelectors = [] } = {}) {
  return {
    name: '@dazzlabs/dazzui-ds-plugin-runtime',
    build({ tokens, outputFile }) {
      outputFile('runtime.ts', generate(resolveThemes(tokens, modeSelectors)))
    },
  }
}
