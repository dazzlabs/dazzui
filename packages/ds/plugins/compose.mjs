/** Material 3 owns the components; ds supplies only their color roles. */
export default function composePlugin({ modeSelectors = [] } = {}) {
  return {
    name: '@dazzlabs/dazzui-ds-plugin-compose',
    async build({ tokens, outputFile }) {
      outputFile(
        'compose/DazzColorSchemes.kt',
        renderSchemes(tokens, modeSelectors)
      )
    },
  }
}

export function renderSchemes(tokens, modeSelectors) {
  const themes = new Map([['studio-light', []]])
  for (const { mode, selectors = [] } of modeSelectors) {
    for (const selector of selectors) {
      const name = /\[data-theme='([^']+)'\]/.exec(selector)?.[1]
      if (!name) continue
      if (!themes.has(name)) themes.set(name, [])
      themes.get(name).push(mode)
    }
  }
  const schemes = new Map(
    [...themes].map(([name, modes]) => [name, roles(tokens, modes)])
  )
  const blocks = [...themes].map(([name, modes]) => {
    const colors = { ...schemes.get(name) }
    const light = schemes.get(name.replace(/-dark$/, '-light'))
    if (!light) throw new Error(`Missing light counterpart for ${name}`)
    for (const role of ['primary', 'secondary', 'tertiary']) {
      const on = `on${pascal(role)}`
      colors[`${role}Fixed`] = light[`${role}Container`]
      colors[`${role}FixedDim`] = light[`${role}FixedDim`]
      colors[`${on}Fixed`] = light[`${on}Container`]
      colors[`${on}FixedVariant`] = light[`${on}Container`]
    }
    return `    val ${pascal(name)}: ColorScheme = ${modes.includes('dark') ? 'dark' : 'light'}ColorScheme(\n${Object.entries(
      colors
    )
      .map(([role, color]) => `        ${role} = ${literal(color)},`)
      .join('\n')}\n    )`
  })
  const families = [
    ...new Set(
      [...themes.keys()].map(name => name.replace(/-(light|dark)$/, ''))
    ),
  ]
  return `// Generated by packages/ds. Do not edit. Run pnpm tokens.\npackage dev.dazzlabs.dazzui.mobile.generated\n\nimport androidx.compose.material3.ColorScheme\nimport androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.lightColorScheme\nimport androidx.compose.ui.graphics.Color\n\n/** The same theme families as ds; appearance can follow the system. */\nenum class DazzThemeFamily {\n    ${families.map(pascal).join(', ')},\n}\n\nobject DazzColorSchemes {\n${blocks.join('\n\n')}\n}\n\nfun dazzColorScheme(\n    family: DazzThemeFamily = DazzThemeFamily.Studio,\n    darkTheme: Boolean = false,\n): ColorScheme = when (family) {\n${families.map(f => `    DazzThemeFamily.${pascal(f)} -> if (darkTheme) DazzColorSchemes.${pascal(f)}Dark else DazzColorSchemes.${pascal(f)}Light`).join('\n')}\n}\n`
}

function roles(tokens, modes) {
  const value = id => {
    const token = tokens[id]
    if (!token) throw new Error(`Missing Compose color input: ${id}`)
    let result = token.$value
    for (const mode of modes)
      if (token.mode?.[mode]) result = token.mode[mode].$value
    return result
  }
  const color = id => rgba(value(id))
  const paper = color('color.surface')
  const ink = color('color.content')
  const recipe = (variant, part, tint, state = 'normal') => {
    const base = `control.color.${variant}.${part}.${state}`
    const c = tokens[`${base}.color`]
      ? color(`${base}.color`)
      : color(`color.${tint}.${value(`${base}.shade`)}`)
    const alpha = tokens[`${base}.alpha`] ? value(`${base}.alpha`) : 1
    return [...c.slice(0, 3), c[3] * alpha]
  }
  // Material containers are opaque surfaces. Composite ds's tint wash once,
  // over the theme paper, rather than letting the host background change it.
  const container = tint => over(recipe('tinted', 'surface', tint), paper)
  const primary = recipe('filled', 'surface', 'primary')
  const tertiary = recipe('filled', 'surface', 'info')
  const error = recipe('filled', 'surface', 'danger')
  // on-accent is specific to the brand (acid text in Bright), so semantic
  // fills choose the more legible of this theme's paper and ink instead.
  const onFill = fill => {
    const preferred = contrast(paper, fill) >= contrast(ink, fill) ? paper : ink
    if (contrast(preferred, fill) >= 4.5) return preferred
    // Some warm papers and navy inks both miss normal-text contrast on red.
    // Fall back to ds primitives, keeping semantic controls readable.
    const white = color('base.color.white')
    const black = color('base.color.black')
    return contrast(white, fill) >= contrast(black, fill) ? white : black
  }
  return {
    primary,
    onPrimary: color('color.on-accent'),
    primaryContainer: container('primary'),
    onPrimaryContainer: recipe('tinted', 'content', 'primary'),
    inversePrimary: color('color.on-accent'),
    secondary: color('color.content-secondary'),
    onSecondary: paper,
    secondaryContainer: color('color.surface-inset'),
    onSecondaryContainer: ink,
    tertiary,
    onTertiary: onFill(tertiary),
    tertiaryContainer: container('info'),
    onTertiaryContainer: recipe('tinted', 'content', 'info'),
    background: color('color.canvas'),
    onBackground: ink,
    surface: paper,
    onSurface: ink,
    surfaceVariant: color('color.surface-inset'),
    onSurfaceVariant: color('color.content-muted'),
    surfaceTint: primary,
    inverseSurface: ink,
    inverseOnSurface: paper,
    error,
    onError: onFill(error),
    errorContainer: container('danger'),
    onErrorContainer: recipe('tinted', 'content', 'danger'),
    outline: color('color.border-muted'),
    outlineVariant: color('color.border'),
    // Material applies its own scrim opacity.
    scrim: color('base.color.black'),
    surfaceBright: color('color.surface-raised'),
    surfaceDim: color('color.surface-sunken'),
    surfaceContainerLowest: color('color.canvas'),
    surfaceContainerLow: color('color.surface-column'),
    surfaceContainer: color('color.surface-muted'),
    surfaceContainerHigh: color('color.surface-overlay'),
    surfaceContainerHighest: color('color.surface-raised'),
    primaryFixedDim: over(
      recipe('tinted', 'surface', 'primary', 'hovered'),
      paper
    ),
    secondaryFixedDim: color('color.surface-sunken'),
    tertiaryFixedDim: over(
      recipe('tinted', 'surface', 'info', 'hovered'),
      paper
    ),
  }
}

function rgba(value) {
  if (typeof value === 'string' && /^#[\da-f]{6}([\da-f]{2})?$/i.test(value)) {
    return [1, 3, 5]
      .map(i => parseInt(value.slice(i, i + 2), 16) / 255)
      .concat(value.length === 9 ? parseInt(value.slice(7), 16) / 255 : 1)
  }
  if (value?.colorSpace === 'srgb')
    return [...value.components, value.alpha ?? 1]
  if (value?.colorSpace === 'oklch') {
    const [l, c, h] = value.components
    const a = c * Math.cos((h * Math.PI) / 180)
    const b = c * Math.sin((h * Math.PI) / 180)
    const x = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    const y = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    const z = (l - 0.0894841775 * a - 1.291485548 * b) ** 3
    return [
      4.0767416621 * x - 3.3077115913 * y + 0.2309699292 * z,
      -1.2684380046 * x + 2.6097574011 * y - 0.3413193965 * z,
      -0.0041960863 * x - 0.7034186147 * y + 1.707614701 * z,
    ]
      .map(v =>
        Math.max(
          0,
          Math.min(
            1,
            v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055
          )
        )
      )
      .concat(value.alpha ?? 1)
  }
  throw new Error(`Unsupported Compose color: ${JSON.stringify(value)}`)
}

function over(fg, bg) {
  return fg
    .slice(0, 3)
    .map((v, i) => v * fg[3] + bg[i] * (1 - fg[3]))
    .concat(1)
}
function contrast(a, b) {
  const luminance = c =>
    c
      .slice(0, 3)
      .map(v => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
      .reduce((sum, v, i) => sum + v * [0.2126, 0.7152, 0.0722][i], 0)
  const [hi, lo] = [luminance(over(a, b)), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}
function literal(c) {
  return `Color(0x${[c[3], ...c.slice(0, 3)]
    .map(v =>
      Math.round(v * 255)
        .toString(16)
        .padStart(2, '0')
    )
    .join('')
    .toUpperCase()})`
}
function pascal(name) {
  return name
    .split('-')
    .map(s => s[0].toUpperCase() + s.slice(1))
    .join('')
}
